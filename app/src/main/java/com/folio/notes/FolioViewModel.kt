package com.folio.notes

import android.app.Application
import android.net.Uri
import androidx.lifecycle.AndroidViewModel
import androidx.lifecycle.SavedStateHandle
import androidx.lifecycle.viewModelScope
import kotlinx.coroutines.*
import kotlinx.coroutines.flow.distinctUntilChanged

/** Compatibility presentation port. Content, history and writes live for the application lifetime. */
class FolioViewModel(application: Application, savedState: SavedStateHandle) : AndroidViewModel(application) {
    private val runtime = (application as FolioApplication).runtime
    val state = runtime.state
    val shellState = runtime.shellState
    val documents: DocumentReader = runtime._state
    val repository = runtime.repository
    val thumbnails = runtime.thumbnails
    val imageFiles = runtime.imageFiles
    var pendingExport: PageExportRequest?
        get() = runtime.pendingExport
        set(value) { runtime.pendingExport = value }

    init {
        runtime.restoreSession(savedState)
        viewModelScope.launch {
            state.distinctUntilChanged { a, b ->
                a.activeId == b.activeId && a.pageIndex == b.pageIndex && a.folderId == b.folderId &&
                    a.tabs == b.tabs && a.companion == b.companion && a.companionMode == b.companionMode &&
                    a.splitFraction == b.splitFraction && a.companionLinked == b.companionLinked &&
                    a.companionHostId == b.companionHostId && a.editorOnRight == b.editorOnRight && a.pdfSearch == b.pdfSearch
            }.collect { runtime.copySessionTo(savedState, it) }
        }
    }

    internal fun pageMutations(pageId: String): EditorPageMutations = EnginePageMutations(runtime, pageId)

